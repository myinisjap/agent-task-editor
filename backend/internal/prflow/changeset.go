package prflow

import (
	"fmt"
	"strings"
	"unicode/utf8"
)

// Markers bounding the generated change-set section of a PR body (ADR 0041
// stage 5). Text outside them is never touched.
const (
	SectionBegin = "<!-- ate:change-set:begin -->"
	SectionEnd   = "<!-- ate:change-set:end -->"
	// CommentMarker tags the single fallback comment, so it is posted at most
	// once per PR.
	CommentMarker = "<!-- ate:change-set:comment -->"

	maxFieldRunes = 100
	maxSectionLen = 4000
)

// ChangeSetMember is one task of a change set as rendered in the section.
type ChangeSetMember struct {
	TaskID, Title, RepoName, PRURL string
	IsParent, IsSelf               bool
}

// ChangeSetView is everything RenderSection needs.
type ChangeSetView struct {
	ParentTitle   string
	ParentLink    string // "" = no board base URL configured
	ParentShortID string
	Members       []ChangeSetMember // parent first, then children in created_at order
	MergeOrder    []string          // task ids; empty = no order to show
}

// sanitize makes untrusted text (titles can come from imported issues) safe to
// embed: no HTML-comment delimiters or our markers, single line, truncated.
func sanitize(s string) string {
	for _, bad := range []string{SectionBegin, SectionEnd, CommentMarker, "<!--", "-->"} {
		s = strings.ReplaceAll(s, bad, "")
	}
	s = strings.Join(strings.Fields(s), " ")
	if utf8.RuneCountInString(s) > maxFieldRunes {
		r := []rune(s)
		s = strings.TrimSpace(string(r[:maxFieldRunes])) + "…"
	}
	s = strings.ReplaceAll(s, "`", "'")
	return s
}

// RenderSection renders the generated section. Pure and deterministic.
func RenderSection(v ChangeSetView) string {
	var b strings.Builder
	b.WriteString(SectionBegin + "\n")
	fmt.Fprintf(&b, "### Part of change set: %s\n\n", sanitize(v.ParentTitle))
	if v.ParentLink != "" {
		fmt.Fprintf(&b, "[Open on the board](%s)\n\n", strings.Join(strings.Fields(v.ParentLink), ""))
	} else {
		fmt.Fprintf(&b, "Parent task `%s`\n\n", sanitize(v.ParentShortID))
	}
	pr := func(m ChangeSetMember) string {
		if m.PRURL == "" {
			return "not opened yet"
		}
		return sanitizeURL(m.PRURL)
	}
	names := map[string]ChangeSetMember{}
	for _, m := range v.Members {
		names[m.TaskID] = m
		label := fmt.Sprintf("`%s` · %s · %s", sanitize(m.RepoName), sanitize(m.Title), pr(m))
		if m.IsParent {
			label = "**Parent** · " + label
		}
		if m.IsSelf {
			label += " **(this PR)**"
		}
		b.WriteString("- " + label + "\n")
	}
	if len(v.MergeOrder) > 0 {
		var parts []string
		for i, id := range v.MergeOrder {
			m := names[id]
			parts = append(parts, fmt.Sprintf("%d. `%s` %s", i+1, sanitize(m.RepoName), sanitize(m.Title)))
		}
		b.WriteString("\nIntended merge order: " + strings.Join(parts, " → ") + "\n")
	}
	b.WriteString("\n_Generated by agent-task-editor; edits between these markers are overwritten._\n")
	b.WriteString(SectionEnd)
	out := b.String()
	if len(out) > maxSectionLen {
		// Defense in depth (at most 11 members of <=100 runes each should never hit this).
		tail := "\n…\n" + SectionEnd
		cut := maxSectionLen - len(tail)
		for cut > 0 && !utf8.RuneStart(out[cut]) {
			cut--
		}
		out = out[:cut] + tail
	}
	return out
}

func sanitizeURL(u string) string {
	u = strings.Join(strings.Fields(u), "")
	u = strings.ReplaceAll(u, "<!--", "")
	return strings.ReplaceAll(u, "-->", "")
}

// SpliceSection replaces the marker-bounded section of body with section, or
// appends it when no markers are present. ok=false when the markers are
// malformed (one marker only, duplicates, reversed): the caller must not guess.
func SpliceSection(body, section string) (string, bool) {
	nb, ne := strings.Count(body, SectionBegin), strings.Count(body, SectionEnd)
	if nb == 0 && ne == 0 {
		if strings.TrimSpace(body) == "" {
			return section, true
		}
		return body + "\n\n" + section, true
	}
	if nb != 1 || ne != 1 {
		return body, false
	}
	bi, ei := strings.Index(body, SectionBegin), strings.Index(body, SectionEnd)
	if ei < bi {
		return body, false
	}
	return body[:bi] + section + body[ei+len(SectionEnd):], true
}

// prNumberFromURL parses the trailing /pull/<n> (GitHub) or /pulls/<n> (Gitea).
func prNumberFromURL(u string) (int, bool) {
	u = strings.TrimRight(u, "/")
	i := strings.LastIndex(u, "/")
	if i < 0 {
		return 0, false
	}
	prev := u[:i]
	if !strings.HasSuffix(prev, "/pull") && !strings.HasSuffix(prev, "/pulls") {
		return 0, false
	}
	n := 0
	if _, err := fmt.Sscanf(u[i+1:], "%d", &n); err != nil || n <= 0 || fmt.Sprint(n) != u[i+1:] {
		return 0, false
	}
	return n, true
}
