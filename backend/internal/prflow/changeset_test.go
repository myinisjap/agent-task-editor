func TestSyncChangeSetLinks(t *testing.T) {
	ctx := context.Background()
	e := setupCS(t, true)
	e.setPR(t, &e.frgn, "5")
	e.f.body = "human intro"
	if err := e.svc.SyncChangeSetLinks(ctx, e.frgn); err != nil {
		t.Fatal(err)
	}
	if e.f.edits != 1 || !strings.HasPrefix(e.f.body, "human intro\n\n"+SectionBegin) {
		t.Fatalf("edits=%d body=%q", e.f.edits, e.f.body)
	}
	// Idempotent retry: no further edit.
	if err := e.svc.SyncChangeSetLinks(ctx, e.frgn); err != nil || e.f.edits != 1 {
		t.Fatalf("retry: err=%v edits=%d", err, e.f.edits)
	}
	// A human edit outside the markers survives when a sibling PR appears.
	e.f.body = "EDITED " + e.f.body + " tail"
	e.setPR(t, &e.parent, "9")
	if err := e.svc.SyncChangeSetLinks(ctx, e.frgn); err != nil {
		t.Fatal(err)
	}
	if e.f.edits != 2 || !strings.HasPrefix(e.f.body, "EDITED human intro") || !strings.HasSuffix(e.f.body, SectionEnd+" tail") ||
		!strings.Contains(e.f.body, "/pull/9") {
		t.Fatalf("edits=%d body=%q", e.f.edits, e.f.body)
	}
}

