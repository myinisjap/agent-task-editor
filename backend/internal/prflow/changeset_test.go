func sampleView() ChangeSetView {
	return ChangeSetView{
		ParentTitle: "Add widgets", ParentLink: "https://board.test/tasks/p1", ParentShortID: "p1",
		Members: []ChangeSetMember{
			{TaskID: "p1", Title: "Add widgets", RepoName: "main", IsParent: true},
			{TaskID: "a", Title: "API", RepoName: "api", PRURL: "https://github.com/o/api/pull/3", IsSelf: true},
			{TaskID: "b", Title: "Client", RepoName: "client"},
		},
	}
}

func TestRenderSection_Golden(t *testing.T) {
	v := sampleView()
	v.MergeOrder = []string{"a", "b"}
	want := `<!-- ate:change-set:begin -->
### Part of change set: Add widgets

[Open on the board](https://board.test/tasks/p1)

- **Parent** · ` + "`main`" + ` · Add widgets · not opened yet
- ` + "`api`" + ` · API · https://github.com/o/api/pull/3 **(this PR)**
- ` + "`client`" + ` · Client · not opened yet

Intended merge order: 1. ` + "`api`" + ` API → 2. ` + "`client`" + ` Client

_Generated by agent-task-editor; edits between these markers are overwritten._
<!-- ate:change-set:end -->`
	if got := RenderSection(v); got != want {
		t.Fatalf("got:\n%s\nwant:\n%s", got, want)
	}
}

func TestRenderSection_NoLinkNoOrder(t *testing.T) {
	v := sampleView()
	v.ParentLink = ""
	got := RenderSection(v)
	if strings.Contains(got, "Open on the board") || !strings.Contains(got, "Parent task `p1`") {
		t.Fatalf("no-link rendering wrong:\n%s", got)
	}
	if strings.Contains(got, "merge order") {
		t.Fatalf("merge order must be omitted:\n%s", got)
	}
}

func TestRenderSection_Sanitizes(t *testing.T) {
	v := sampleView()
	v.Members[2].Title = "evil --> " + SectionEnd + " <!-- x\nsecond line " + strings.Repeat("z", 300)
	got := RenderSection(v)
	if strings.Count(got, SectionBegin) != 1 || strings.Count(got, SectionEnd) != 1 {
		t.Fatalf("markers not unique:\n%s", got)
	}
	if strings.Contains(got, "-->\n") && strings.Count(got, "-->") != 2 {
		t.Fatalf("injected comment delimiter survived:\n%s", got)
	}
	if strings.Count(got, "\n- ") != 3 || !strings.Contains(got, "…") {
		t.Fatalf("expected 3 single-line items and truncation:\n%s", got)
	}
	// Splice of a rendered section is stable.
	if _, ok := SpliceSection("hi\n\n"+got, got); !ok {
		t.Fatal("rendered section must splice")
	}
}

func TestSpliceSection(t *testing.T) {
	sec := RenderSection(sampleView())
	old := SectionBegin + "\nold\n" + SectionEnd
	body := "human before\n\n" + old + "\n\nhuman after (edited)"
	got, ok := SpliceSection(body, sec)
	if !ok || got != "human before\n\n"+sec+"\n\nhuman after (edited)" {
		t.Fatalf("replace wrong: %v\n%s", ok, got)
	}
	if got2, _ := SpliceSection(got, sec); got2 != got {
		t.Fatal("splice must be idempotent")
	}
	if got, ok := SpliceSection("text", sec); !ok || got != "text\n\n"+sec {
		t.Fatalf("append: %q", got)
	}
	if got, ok := SpliceSection("  \n", sec); !ok || got != sec {
		t.Fatalf("empty body: %q", got)
	}
	for name, bad := range map[string]string{
		"only begin": "a " + SectionBegin,
		"only end":   "a " + SectionEnd,
		"dup":        old + old,
		"reversed":   SectionEnd + " x " + SectionBegin,
	} {
		if got, ok := SpliceSection(bad, sec); ok || got != bad {
			t.Errorf("%s: want ok=false untouched, got ok=%v", name, ok)
		}
	}
}

